# Function to add two numbers
def add_numbers(num1, num2):
    return num1 + num2

# Function to subtract two numbers
def subtract_numbers(num1, num2):
    return num1 - num2

# Function to multiply two numbers
def multiply_numbers(num1, num2):
    return num1 * num2

# Function to divide two numbers with safety check
def divide_numbers(num1, num2):
    if num2 == 0:
        return "Error: Cannot divide by zero."
    return num1 / num2

def main():
    print("=== MODULAR CALCULATOR ===")

    # Ask the user to enter two numbers
    num1 = float(input("Enter first number: "))
    num2 = float(input("Enter second number: "))

    # Display operation choices clearly
    print("\nChoose an operation:")
    print("1 - Addition (+)")
    print("2 - Subtraction (-)")
    print("3 - Multiplication (*)")
    print("4 - Division (/)\n")

    choice = input("Enter choice (1-4): ")

    # Process the user's choice and call the appropriate function
    if choice == '1':
        result = add_numbers(num1, num2)
        operation_name = "Addition"
    elif choice == '2':
        result = subtract_numbers(num1, num2)
        operation_name = "Subtraction"
    elif choice == '3':
        result = multiply_numbers(num1, num2)
        operation_name = "Multiplication"
    elif choice == '4':
        result = divide_numbers(num1, num2)
        operation_name = "Division"
    else:
        result = "Invalid choice selected."
        operation_name = "Unknown"

    # Display the final formatted result
    print(f"\nOperation: {operation_name}")
    print(f"Result: {result}")
    print("==========================")

if __name__ == "__main__":
    main()